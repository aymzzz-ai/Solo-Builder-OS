// project-contract — the instance initializer (ARC-2 host projection + scaffold).
//
// One OS = one business (the repo root IS the instance; CAR-5 = separate clones). This
// script turns a fresh clone of the OS template into a working business instance:
//   1. Projects the single neutral authority (os-core/schema/operating-contract.md) into
//      the host rulebook CLAUDE.md at the repo root. It is GENERATED — never hand-edit;
//      edit the contract and re-run.
//   2. Scaffolds the instance data folders + seed files at the repo root.
//   3. Seeds meta/routines-state.md (the cadence ledger /brief reads, contract §7).
//   4. Emits .claude/settings.json from the host-adapter template
//      (os-core/templates/host-claude-settings.md) — the SessionEnd-harvest +
//      hook (the only routine that needs a host event), plus the CAR-4 deny block.
//   5. Registers the business slug in config/ and seeds non-secret config + a .env example.
//   6. Removes build-only artifacts (test/) so OS-build scaffolding can't drift into the
//      business as hallucinated "knowledge".
//
// It is IDEMPOTENT: generated files (CLAUDE.md/settings.json) are regenerated;
// data/seed files are created only if absent (your content is never clobbered).
//
// Usage:
//   node scripts/project-contract.js <business-slug> [--target <dir>]
//
//   --target <dir>   instance root to scaffold (default: the repo root). Used by tests.
//
// GUARD: refuses to run when the repo carries the `.os-build-workspace` sentinel (i.e. this
// is the OS-build/template repo, not a business instance). To dedicate a clone to a business,
// delete that sentinel first — that is the deliberate "this clone is now a business" gesture.
//
// Exit codes: 0 = initialized · 2 = usage/guard/IO error.
// Reads: os-core/schema/operating-contract.md (authority), os-core/templates/
//        host-claude-settings.md (hook config), config/preferences.md (optional, appended).

const fs = require('fs');
const path = require('path');

const SCRIPT_ROOT = path.resolve(__dirname, '..'); // where os-core/ + templates ship
const CONTRACT = path.join(SCRIPT_ROOT, 'os-core', 'schema', 'operating-contract.md');
const HOST_TPL = path.join(SCRIPT_ROOT, 'os-core', 'templates', 'host-claude-settings.md');
const SENTINEL = '.os-build-workspace';

// Claude Code is the only supported host (ARC-2). The contract is neutral prose, so a
// second host would only need another projection target here.
const RULEBOOK = { file: 'CLAUDE.md', label: 'Claude Code' };

function today() {
  return new Date().toISOString().slice(0, 10);
}

function parseArgs(argv) {
  const out = { slug: null, target: null };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--target') {
      out.target = argv[++i];
    } else if (!out.slug) {
      out.slug = argv[i];
    }
  }
  return out;
}

function header(slug, hostLabel) {
  return [
    `<!-- AUTO-GENERATED by scripts/project-contract.js for business "${slug}" (host: ${hostLabel}).`,
    `     DO NOT HAND-EDIT. Edit os-core/schema/operating-contract.md and re-run this script.`,
    `     Generated: ${new Date().toISOString()} -->`,
    '',
  ].join('\n');
}

// Write only if the file does not already exist (protects user data on re-run).
function writeIfAbsent(file, body, created) {
  if (fs.existsSync(file)) return false;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, body, 'utf8');
  created.push(path.relative(INSTANCE, file));
  return true;
}

// Regenerate (overwrite) — for generated projections.
function writeAlways(file, body) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, body, 'utf8');
}

let INSTANCE; // resolved in main()

function projectContract(slug) {
  const contract = fs.readFileSync(CONTRACT, 'utf8').trimEnd();
  const prefsPath = path.join(INSTANCE, 'config', 'preferences.md');
  let prefsBlock = '';
  if (fs.existsSync(prefsPath)) {
    const prefs = fs.readFileSync(prefsPath, 'utf8').trim();
    if (prefs) prefsBlock = `\n\n---\n\n## Maintainer preferences (this business)\n\n${prefs}\n`;
  }
  const dest = path.join(INSTANCE, RULEBOOK.file);
  writeAlways(dest, `${header(slug, RULEBOOK.label)}${contract}${prefsBlock}\n`);
  console.log(`  projected → ${RULEBOOK.file} (${RULEBOOK.label})`);
}

function scaffoldFolders() {
  const dirs = [
    'raw', 'wiki/concepts', 'wiki/entities', 'wiki/qa',
    'decisions', 'council', 'prds', 'drafts',
    'meta', 'config', '.secrets', '.claude', 'scripts/hooks',
  ];
  for (const d of dirs) fs.mkdirSync(path.join(INSTANCE, d), { recursive: true });
}

// Build-only artifacts that must NOT ride into a business instance — they'd be a drift /
// hallucination source. This only ever fires in a real business clone: the sentinel guard
// blocks the template repo, and the acceptance suite invokes with `--target <tmp>` where
// these paths don't exist.
const BUILD_ONLY = ['test'];

function stripBuildOnly(removed) {
  for (const rel of BUILD_ONLY) {
    const p = path.join(INSTANCE, rel);
    if (fs.existsSync(p)) {
      fs.rmSync(p, { recursive: true, force: true });
      removed.push(rel);
    }
  }
  // The acceptance suite belongs to the OS build, not to a business instance. Leaving
  // `npm test` pointing at the directory we just deleted hands the user a command that
  // only ever fails.
  const pkgPath = path.join(INSTANCE, 'package.json');
  if (!fs.existsSync(pkgPath)) return;
  try {
    const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));
    if (pkg.scripts && pkg.scripts.test) {
      delete pkg.scripts.test;
      fs.writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + '\n');
      removed.push('package.json "test" script');
    }
  } catch {
    // A package.json we can't parse is the user's to fix; scaffolding shouldn't die on it.
  }
}

